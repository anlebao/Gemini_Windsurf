import { chromium } from '@playwright/test';
const browser = await chromium.launch();
const page = await browser.newPage();
page.on('console', m => { if (m.type() === 'error') console.log('CONSOLE-ERR:', m.text().slice(0,200)); });
page.on('pageerror', e => console.log('PAGE-ERR:', String(e).slice(0,300)));
await page.goto('https://commienphi.timlathay.com/stores', { waitUntil: 'domcontentloaded' });
const input = page.locator('#search-input');
await input.waitFor({ state: 'visible', timeout: 90000 });
await input.fill('samo');
await input.press('Enter');
const chip = page.locator('.alert', { hasText: 'Ý bạn là' }).locator('button', { hasText: 'Samho' });
await chip.waitFor({ state: 'visible', timeout: 60000 });
console.log('chip visible, clicking');
await chip.click();
await page.waitForTimeout(5000);
console.log('input value after click:', await input.inputValue());
console.log('alert still present:', await page.locator('.alert', { hasText: 'Ý bạn là' }).count());
console.log('store cards:', await page.locator('.store-card-hover').count());
await browser.close();
